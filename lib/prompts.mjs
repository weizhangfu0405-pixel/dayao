export function signals(stats) {
  const s = [];
  if (stats.国库 < 30) s.push('府库将空，百官俸禄已欠三月');
  if (stats.民心 < 30) s.push('流民已聚于城外，米价一日三涨');
  if (stats.军力 < 30) s.push('京营空额过半，边将自募私兵');
  if (stats.武运 < 30) s.push('江湖凋敝，十年未出新宗师');
  if (stats.威望 < 30) s.push('藩镇观望，诏令出了天枢城便打折扣');
  if (stats.国运 < 25) s.push('钦天监夜观星象，紫微晦暗欲坠');
  if (stats.民心 > 75) s.push('民间称颂，市井已有「永昌之治」的说法');
  if (stats.武运 > 75) s.push('武运鼎盛，江湖新人如过江之鲫');
  return s;
}

const CN = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
function cnYear(n) {
  if (n <= 1) return '元';
  if (n < 10) return CN[n];
  if (n < 20) return '十' + (n % 10 ? CN[n % 10] : '');
  return CN[Math.floor(n / 10)] + '十' + (n % 10 ? CN[n % 10] : '');
}

function stateJson(state) {
  const s = state.stats;
  return JSON.stringify({
    年号: `${state.eraName || '永昌'}${cnYear(state.year)}年`,
    在位第: state.turn + 1,
    国运: s.国运, 民心: s.民心, 国库: s.国库,
    军力: s.军力, 武运: s.武运, 威望: s.威望,
    现状: signals(s),
  });
}

