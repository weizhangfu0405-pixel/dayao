export function turnPrompt(state, chronicleTail, choice) {
  const history = chronicleTail.slice(-6).map((c) => `· ${c}`).join('\n') || '（尚无）';
  const what = choice.kind === 'custom'
    ? `玩家自拟旨意（照此执行，不要质疑，只推演后果）：「${choice.text}」`
    : `玩家选择：「${choice.label}」——${choice.desc}（${choice.tag}）`;

  return `【当前局势】
${stateJson(state)}

【近年纪事】
${history}

【玩家旨意】
${what}

【推演要求】
1. 先写这道旨意如何落地（谁去办、办成几分），再写一个玩家没料到的转折，最后留一个余波或新隐患。
2. outcome 150~210字；chronicle 一句，以「永昌X年」起笔。
3. next 是下一个回合的新局面，必须由本回合的后果生长出来，不能另起炉灶。
4. figure 只在出现新人物时填写，否则 null。
5. ${state.stats.国运 <= 0 ? '国运已尽，必须给出 ending（亡国），next 为 null。' : '除非国运归零或玩家选择封禅（需国运≥92），否则 ending 为 null。'}
6. ${state.stats.国运 >= 88 ? '国运已至高点，next.options 中必须有一项是「封禅」（另一项仍须是务实之举），玩家若选封禅且国运≥92 则给出盛世结局。' : '不要轻易给出封禅之类的选项。'}
7. 只输出 JSON。`;
}
